--                                          画面に表示されたら、権限判定の不具合である。
--
-- 日時は now() からの相対値で入れる（フィードは直近 7 日だけを返すため）。
-- 再実行すると日時も更新する。DB を消さずに再投入するには `docker compose run --rm --no-deps seed` を使う。
