-- seed 対象への手動変更も戻る。seed にない ID の行は削除しない。
--
-- 開発用の認証ガードは、常に 11111111-1111-4111-8111-111111111111（開発ユーザー）として扱う。
-- この利用者の視点で、次の 3 種類のデータを入れる。
--
--   1. 開発ユーザーが所有するデータ     … タスク（全状態）、証拠、投稿、通知、異議、招待リンク
